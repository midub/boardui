#!/usr/bin/env python3
"""Writes the hand-written samples (spec/samples/README.md).

Each sample is a minimal IPC-2581 rev C file for one spec rule (rev A or B where the rule is
about them). Run from any directory:

    python3 spec/samples/hand-written/generate.py

The script only uses the standard library. Coordinates are written in millimetres here and
converted to each file's units.
"""

import base64
import json
import math
import struct
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent
UNITS = {"MILLIMETER": 1.0, "INCH": 1 / 25.4, "MICRON": 1000.0}


class Doc:
    """An IPC-2581 document in one unit system."""

    def __init__(self, units="MILLIMETER", mode="FABRICATION", revision="C"):
        self.units = units
        self.mode = mode
        self.revision = revision
        # Revision A and B `PadStack`s of the main step; they come before its `Datum`.
        self.pad_stacks = []
        self.lines = {}
        self.standard = {}
        self.layers = []
        self.step = []
        self.colors = {}
        self.specs = []
        # Steps written before the main step: (name, datum, elements).
        self.steps = []
        self.step_refs = None
        self.fonts = {}

    def u(self, mm):
        """A length in mm, formatted in the document's units."""
        v = mm * UNITS[self.units]
        return f"{v:.10g}"

    def xy(self, x, y, prefix=""):
        return f'{prefix}x="{self.u(x)}" {prefix}y="{self.u(y)}"'

    def line_desc(self, name, width, end="ROUND", prop=None):
        prop = f' lineProperty="{prop}"' if prop else ""
        self.lines[name] = f'<LineDesc lineWidth="{self.u(width)}" lineEnd="{end}"{prop}/>'

    def primitive(self, name, xml):
        self.standard[name] = xml

    def font(self, name, xml):
        self.fonts[name] = xml

    def color(self, name, r, g, b):
        self.colors[name] = f'<Color r="{r}" g="{g}" b="{b}"/>'

    def spec(self, name, xml):
        self.specs.append(f'<Spec name="{name}">{xml}</Spec>')

    def layer(self, name, function, side, span=None, specs=()):
        inner = "".join(f'<SpecRef id="{s}"/>' for s in specs)
        inner += f'<Span fromLayer="{span[0]}" toLayer="{span[1]}"/>' if span else ""
        self.layers.append(
            f'<Layer name="{name}" layerFunction="{function}" side="{side}">{inner}</Layer>'
        )

    def polygon(self, points, close=True):
        (x0, y0), rest = points[0], points[1:]
        steps = "".join(f"<PolyStepSegment {self.xy(x, y)}/>" for x, y in rest)
        if close:
            steps += f"<PolyStepSegment {self.xy(x0, y0)}/>"
        return f"<PolyBegin {self.xy(x0, y0)}/>{steps}"

    def rect(self, x0, y0, x1, y1):
        return self.polygon([(x0, y0), (x1, y0), (x1, y1), (x0, y1)])

    def add_step(self, name, datum, elements):
        self.steps.append((name, datum, elements))

    def write(self, path, name, step_name="board"):
        dict_units = f'units="{self.units}"'
        lines = "".join(
            f'<EntryLineDesc id="{k}">{v}</EntryLineDesc>' for k, v in self.lines.items()
        )
        standard = "".join(
            f'<EntryStandard id="{k}">{v}</EntryStandard>' for k, v in self.standard.items()
        )
        colors = "".join(f'<EntryColor id="{k}">{v}</EntryColor>' for k, v in self.colors.items())
        colors = f"\n    <DictionaryColor>{colors}</DictionaryColor>" if colors else ""
        fonts = "".join(
            f'\n      <EntryFont id="{k}">{v}</EntryFont>' for k, v in self.fonts.items()
        )
        if fonts:
            fonts = f"\n    <DictionaryFont {dict_units}>{fonts}\n    </DictionaryFont>"
        header = f'<CadHeader units="{self.units}"/>'
        if self.specs:
            specs = "".join(f"\n      {s}" for s in self.specs)
            header = f'<CadHeader units="{self.units}">{specs}\n    </CadHeader>'
        step_refs = "".join(
            f'\n    <StepRef name="{s}"/>' for s in (self.step_refs or [step_name])
        )
        steps = "".join(
            f'\n      <Step name="{s}">\n        <Datum {self.xy(*datum)}/>'
            + "".join(f"\n        {e}" for e in elements)
            + "\n      </Step>"
            for s, datum, elements in self.steps
        )
        xml = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- {name}: hand-written boardui sample, generated by generate.py. -->
<IPC-2581 revision="{self.revision}" xmlns="http://webstds.ipc.org/2581">
  <Content>
    <FunctionMode mode="{self.mode}"/>{step_refs}
    <DictionaryLineDesc {dict_units}>{lines}</DictionaryLineDesc>{fonts}
    <DictionaryStandard {dict_units}>{standard}</DictionaryStandard>{colors}
  </Content>
  <Ecad name="{name}">
    {header}
    <CadData>
      {chr(10).join("      " + l for l in self.layers).strip()}{steps}
      <Step name="{step_name}">{"".join(chr(10) + "        " + p for p in self.pad_stacks)}
        <Datum x="0" y="0"/>
{chr(10).join("        " + s for s in self.step)}
      </Step>
    </CadData>
  </Ecad>
</IPC-2581>
"""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(xml)


def two_layers(d, drill=True):
    d.layer("TOP", "CONDUCTOR", "TOP")
    d.layer("BOTTOM", "CONDUCTOR", "BOTTOM")
    if drill:
        d.layer("DRILL", "DRILL", "ALL", span=("TOP", "BOTTOM"))


def profile(d, w, h):
    d.step.append(f"<Profile><Polygon>{d.rect(0, 0, w, h)}</Polygon></Profile>")


def pad(d, x, y, shape, pin=None, rotation=None):
    xform = f'<Xform rotation="{rotation:g}"/>' if rotation else ""
    pin_ref = f'<PinRef componentRef="{pin[0]}" pin="{pin[1]}"/>' if pin else ""
    return (
        f"<Pad>{xform}<Location {d.xy(x, y)}/>"
        f'<StandardPrimitiveRef id="{shape}"/>{pin_ref}</Pad>'
    )


def trace(d, points, line):
    return (
        f'<Features><Location x="0" y="0"/><Polyline>{d.polygon(points, close=False)}'
        f'<LineDescRef id="{line}"/></Polyline></Features>'
    )


def fill(d, x0, y0, x1, y1):
    return (
        f'<Features><Location x="0" y="0"/><Contour><Polygon>{d.rect(x0, y0, x1, y1)}'
        f"</Polygon></Contour></Features>"
    )


def minimal(units, revision="C"):
    """One resistor, two pads, one trace, one via (spec §4–§8)."""
    d = Doc(units, revision=revision)
    d.line_desc("TRACE", 0.25)
    d.line_desc("OUTLINE", 0.1)
    d.primitive("PAD", f'<RectCenter width="{d.u(0.9)}" height="{d.u(1.0)}"/>')
    d.primitive("VIA", f'<Circle diameter="{d.u(0.6)}"/>')
    two_layers(d)
    profile(d, 10, 6)
    d.step.append(
        f'<Package name="R0603" type="RESISTOR" pinOne="1" height="{d.u(0.5)}">'
        f'<Outline><Polygon>{d.rect(-1.2, -0.6, 1.2, 0.6)}</Polygon><LineDescRef id="OUTLINE"/></Outline>'
        f'<Pin number="1"><Location {d.xy(-0.8, 0)}/><StandardPrimitiveRef id="PAD"/></Pin>'
        f'<Pin number="2"><Location {d.xy(0.8, 0)}/><StandardPrimitiveRef id="PAD"/></Pin>'
        f"</Package>"
    )
    d.step.append(
        f'<Component refDes="R1" packageRef="R0603" layerRef="TOP" part="RES-10K" '
        f'mountType="SMT" standoff="0" height="{d.u(0.5)}"><Location {d.xy(3, 3)}/></Component>'
    )
    d.step.append(
        '<LayerFeature layerRef="TOP">'
        f'<Set net="N1" padUsage="TERMINATION">{pad(d, 2.2, 3, "PAD", ("R1", "1"))}</Set>'
        f'<Set net="N2" padUsage="TERMINATION">{pad(d, 3.8, 3, "PAD", ("R1", "2"))}</Set>'
        f'<Set net="N2">{trace(d, [(3.8, 3), (7, 3)], "TRACE")}</Set>'
        f'<Set net="N2" padUsage="VIA">{pad(d, 7, 3, "VIA")}</Set>'
        "</LayerFeature>"
    )
    d.step.append(
        '<LayerFeature layerRef="BOTTOM">'
        f'<Set net="N2" padUsage="VIA">{pad(d, 7, 3, "VIA")}</Set>'
        "</LayerFeature>"
    )
    d.step.append(
        '<LayerFeature layerRef="DRILL"><Set net="N2">'
        f'<Hole name="H1" diameter="{d.u(0.3)}" platingStatus="VIA" plusTol="0" minusTol="0" {d.xy(7, 3)}/>'
        "</Set></LayerFeature>"
    )
    return d


def pad_stack(d, net, pads, hole=None):
    """A revision A/B `PadStack`: `pads` are `(layer, x, y, shape, pin)`, `hole` is
    `(name, x, y, diameter, platingStatus)` spanning TOP to BOTTOM."""
    inner = ""
    if hole:
        name, x, y, diameter, plating = hole
        inner += (
            f'<LayerHole name="{name}" diameter="{d.u(diameter)}" platingStatus="{plating}" '
            f'plusTol="0" minusTol="0" {d.xy(x, y)}><Span fromLayer="TOP" toLayer="BOTTOM"/></LayerHole>'
        )
    for layer, x, y, shape, pin in pads:
        pin_ref = f'<PinRef componentRef="{pin[0]}" pin="{pin[1]}"/>' if pin else ""
        inner += (
            f'<LayerPad layerRef="{layer}"><Location {d.xy(x, y)}/>'
            f'<StandardPrimitiveRef id="{shape}"/>{pin_ref}</LayerPad>'
        )
    net = f' net="{net}"' if net else ""
    d.pad_stacks.append(f"<PadStack{net}>{inner}</PadStack>")


def pad_stacks():
    """`minimal-2layer` as revision B `PadStack`s, plus a mounting hole, without a drill
    layer: pad and via features with their nets and pins, holes on a synthesized drill layer
    (spec §6.3)."""
    d = minimal("MILLIMETER", revision="B")
    d.layers = [l for l in d.layers if 'name="DRILL"' not in l]
    d.step = [e for e in d.step if not e.startswith("<LayerFeature")]
    pad_stack(d, "N1", [("TOP", 2.2, 3, "PAD", ("R1", "1"))])
    pad_stack(d, "N2", [("TOP", 3.8, 3, "PAD", ("R1", "2"))])
    pad_stack(
        d, "N2", [("TOP", 7, 3, "VIA", None), ("BOTTOM", 7, 3, "VIA", None)], ("V1", 7, 3, 0.3, "VIA")
    )
    pad_stack(d, None, [], ("MH1", 8.5, 1.2, 1.0, "NONPLATED"))
    d.step.append(
        f'<LayerFeature layerRef="TOP"><Set net="N2">{trace(d, [(3.8, 3), (7, 3)], "TRACE")}</Set></LayerFeature>'
    )
    return d


def pad_stacks_drill_layer():
    """Revision A `PadStack` holes that an Altium-style `Drill Guide` layer also has: the drill
    layer's hole is kept and takes the padstack's net; a hole it lacks is added to it (spec
    §6.3)."""
    d = Doc(revision="A")
    d.primitive("VIA", f'<Circle diameter="{d.u(0.6)}"/>')
    d.layer("TOP", "SIGNAL", "TOP")
    d.layer("BOTTOM", "SIGNAL", "BOTTOM")
    d.layer("Drill Guide", "DRILL", "INTERNAL")
    profile(d, 8, 4)
    for name, x in (("V1", 2), ("V2", 6)):
        lands = [("TOP", x, 2, "VIA", None), ("BOTTOM", x, 2, "VIA", None)]
        pad_stack(d, "GND", lands, (name, x, 2, 0.3, "VIA"))
    d.step.append(
        '<LayerFeature layerRef="Drill Guide"><Set>'
        f'<Hole name="Via Hole Drill 0" diameter="{d.u(0.3)}" platingStatus="VIA" plusTol="0" minusTol="0" {d.xy(2, 2)}/>'
        "</Set></LayerFeature>"
    )
    return d


def conductor_core():
    """Altium's core: a `CONDUCTOR` layer with `side="NONE"` and `materialType="FR-4"` in the
    revision A stack-up is a dielectric (spec §6.4)."""
    d = Doc(revision="A")
    d.line_desc("TRACE", 0.25)
    d.layer("Top Layer", "SIGNAL", "TOP")
    d.layer("Dielectric 1", "CONDUCTOR", "NONE")
    d.layer("Bottom Layer", "SIGNAL", "BOTTOM")
    rows = "".join(
        f'<StackupLayer layerOrGroupRef="{name}" materialType="{material}" thickness="{d.u(t)}"/>'
        for name, material, t in (
            ("Top Layer", "Copper", 0.035),
            ("Dielectric 1", "FR-4", 0.32),
            ("Bottom Layer", "Copper", 0.035),
        )
    )
    d.layers.append(f'<Stackup name="S"><StackupGroup name="G">{rows}</StackupGroup></Stackup>')
    profile(d, 6, 4)
    for layer, y in (("Top Layer", 1.5), ("Bottom Layer", 2.5)):
        d.step.append(
            f'<LayerFeature layerRef="{layer}"><Set net="N">{trace(d, [(1, y), (5, y)], "TRACE")}</Set></LayerFeature>'
        )
    return d


def overlap_priority():
    """Pad over trace over plane, and ties in document order (spec §6.2)."""
    d = Doc()
    d.line_desc("WIDE", 0.5)
    d.line_desc("THIN", 0.3)
    d.primitive("PAD", f'<Circle diameter="{d.u(1.2)}"/>')
    d.layer("TOP", "CONDUCTOR", "TOP")
    profile(d, 10, 4)
    d.step.append(
        '<LayerFeature layerRef="TOP">'
        # 0: a plane, the lowest priority.
        f'<Set net="GND">{fill(d, 0, 0, 8, 4)}</Set>'
        # 1: a trace across the plane.
        f'<Set net="SIG">{trace(d, [(1, 2), (7, 2)], "WIDE")}</Set>'
        # 2: a pad on the trace.
        f'<Set net="SIG" padUsage="TERMINATION">{pad(d, 4, 2, "PAD")}</Set>'
        # 3: a second plane overlapping the first: the earlier one keeps the overlap.
        f'<Set net="GND">{fill(d, 6, 1, 10, 3)}</Set>'
        # 4: a second trace crossing the first: the earlier one keeps the crossing.
        f'<Set net="SIG2">{trace(d, [(2, 3.5), (2, 0.5)], "THIN")}</Set>'
        "</LayerFeature>"
    )
    return d


