def outline_cutouts():
    """Cut-outs drawn only on a `BOARD_OUTLINE` layer, as KiCad writes them (spec §6.7).

    The profile (30 × 20 mm with rounded corners) has no `Cutout`. Layer `Edge.Cuts` draws the
    profile again and, as separate lines and arcs in no particular order, some of them reversed
    and with ends up to 8 µm apart, a keyhole (KiCad's from Fomu), a round hole (one arc that
    ends where it starts) and a slot (a closed `Polyline`). These three are cut out. An open
    contour, a square across the board edge and the profile itself are not.
    """
    d = Doc()
    d.line_desc("EDGE", 0.05)
    two_layers(d, drill=False)
    d.layer("Edge.Cuts", "BOARD_OUTLINE", "ALL")

    def curve(x, y, cx, cy, clockwise=False):
        return (
            f'<PolyStepCurve {d.xy(x, y)} centerX="{d.u(cx)}" centerY="{d.u(cy)}" '
            f'clockwise="{str(clockwise).lower()}"/>'
        )

    def line(x0, y0, x1, y1):
        return (
            f'<Line startX="{d.u(x0)}" startY="{d.u(y0)}" endX="{d.u(x1)}" endY="{d.u(y1)}">'
            '<LineDescRef id="EDGE"/></Line>'
        )

    def arc(x0, y0, x1, y1, cx, cy, clockwise):
        return (
            f'<Arc startX="{d.u(x0)}" startY="{d.u(y0)}" endX="{d.u(x1)}" endY="{d.u(y1)}" '
            f'centerX="{d.u(cx)}" centerY="{d.u(cy)}" clockwise="{str(clockwise).lower()}">'
            '<LineDescRef id="EDGE"/></Arc>'
        )

    outline = (
        f"<PolyBegin {d.xy(1, 0)}/><PolyStepSegment {d.xy(29, 0)}/>{curve(30, 1, 29, 1)}"
        f"<PolyStepSegment {d.xy(30, 19)}/>{curve(29, 20, 29, 19)}"
        f"<PolyStepSegment {d.xy(1, 20)}/>{curve(0, 19, 1, 19)}"
        f"<PolyStepSegment {d.xy(0, 1)}/>{curve(1, 0, 1, 1)}"
    )
    d.step.append(f"<Profile><Polygon>{outline}</Polygon></Profile>")
    edges = [
        # The profile itself.
        line(1, 0, 29, 0), arc(29, 0, 30, 1, 29, 1, False), line(30, 1, 30, 19),
        arc(30, 19, 29, 20, 29, 19, False), line(29, 20, 1, 20), arc(1, 20, 0, 19, 1, 19, False),
        line(0, 19, 0, 1), arc(0, 1, 1, 0, 1, 1, False),
        # The keyhole around (8, 10): the top arc ends 8 µm short, the line is reversed.
        arc(8.6, 9.15, 7.4, 9.15, 8, 9.15, True),
        arc(7.4, 10.85, 8.592, 10.85, 8, 10.85, True),
        line(8.6, 9.15, 8.6, 10.85),
        arc(7.4, 9.15, 7.4, 10.85, 7.4, 10, True),
        # A round hole: one arc that ends where it starts.
        arc(17.5, 10, 17.5, 10, 16, 10, False),
        # An open contour: three sides of a rectangle.
        line(20, 4, 26, 4), line(26, 4, 26, 7), line(26, 7, 20, 7),
        # A square across the board edge.
        line(27, 8, 32, 8), line(32, 8, 32, 12), line(32, 12, 27, 12), line(27, 12, 27, 8),
    ]
    slot = (
        f"<PolyBegin {d.xy(20, 13.25)}/><PolyStepSegment {d.xy(25, 13.25)}/>"
        f"{curve(25, 14.75, 25, 14)}<PolyStepSegment {d.xy(20, 14.75)}/>{curve(20, 13.25, 20, 14)}"
    )
    d.step.append(
        '<LayerFeature layerRef="Edge.Cuts">'
        f'<Set><Features><UserSpecial>{"".join(edges)}</UserSpecial></Features></Set>'
        f'<Set><Features><Location x="0" y="0"/><Polyline>{slot}<LineDescRef id="EDGE"/></Polyline></Features></Set>'
        "</LayerFeature>"
    )
    return d


def pinless_package():
    """Components without pads get no placeholder body unless they give a height (spec §6.8).

    No package gives a height, as in KiCad's files. R1 (`SMT`, with pads) gets a body half its
    outline's smaller side high. LOGO1 (a package without pins whose `pinOne` is `UNKNOWN`, as
    KiCad writes logos) and H1 (a mounting hole: one pin that no pad references) get none, and
    the logo's `pinOne` is not reported. LOGO2, the same logo with a component `height`, gets a
    body.
    """
    d = Doc()
    d.line_desc("OUTLINE", 0.1)
    d.primitive("PAD", f'<RectCenter width="{d.u(0.9)}" height="{d.u(1.0)}"/>')
    d.primitive("HOLE", f'<Circle diameter="{d.u(3.2)}"/>')
    two_layers(d)
    profile(d, 25, 15)
    d.step.append(
        '<Package name="R0603" type="RESISTOR" pinOne="1">'
        f'<Outline><Polygon>{d.rect(-1.2, -0.6, 1.2, 0.6)}</Polygon><LineDescRef id="OUTLINE"/></Outline>'
        f'<Pin number="1"><Location {d.xy(-0.8, 0)}/><StandardPrimitiveRef id="PAD"/></Pin>'
        f'<Pin number="2"><Location {d.xy(0.8, 0)}/><StandardPrimitiveRef id="PAD"/></Pin>'
        "</Package>"
    )
    d.step.append(
        '<Package name="LOGO" type="OTHER" pinOne="UNKNOWN">'
        f'<Outline><Polygon>{d.rect(-2, -1, 2, 1)}</Polygon><LineDescRef id="OUTLINE"/></Outline>'
        "</Package>"
    )
    d.step.append(
        '<Package name="MountingHole_3.2mm" type="OTHER" pinOne="1">'
        f'<Outline><Polygon>{d.rect(-1.8, -1.8, 1.8, 1.8)}</Polygon><LineDescRef id="OUTLINE"/></Outline>'
        f'<Pin number="1"><Location {d.xy(0, 0)}/><StandardPrimitiveRef id="HOLE"/></Pin>'
        "</Package>"
    )
    for ref, package, mount, x, y, height in [
        ("R1", "R0603", "SMT", 5, 7.5, None),
        ("LOGO1", "LOGO", "SMT", 12, 10, None),
        ("LOGO2", "LOGO", "SMT", 12, 5, 0.3),
        ("H1", "MountingHole_3.2mm", "THMT", 20, 7.5, None),
    ]:
        height = f' height="{d.u(height)}"' if height else ""
        d.step.append(
            f'<Component refDes="{ref}" packageRef="{package}" layerRef="TOP" '
            f'mountType="{mount}"{height}><Location {d.xy(x, y)}/></Component>'
        )
    d.step.append(
        '<LayerFeature layerRef="TOP">'
        f'<Set net="N1" padUsage="TERMINATION">{pad(d, 4.2, 7.5, "PAD", ("R1", "1"))}</Set>'
        f'<Set net="N2" padUsage="TERMINATION">{pad(d, 5.8, 7.5, "PAD", ("R1", "2"))}</Set>'
        "</LayerFeature>"
    )
    d.step.append(
        '<LayerFeature layerRef="DRILL"><Set>'
        f'<Hole name="H1" diameter="{d.u(3.2)}" platingStatus="NONPLATED" plusTol="0" minusTol="0" {d.xy(20, 7.5)}/>'
        "</Set></LayerFeature>"
    )
    return d


def board_sized_package():
    """A placeholder body covering more than half of its board is left out (spec §6.8).

    U1's footprint is the board itself, as for a carrier board made to drop in for a module
    (MIAO's XIAO footprint): its outline covers the 20 × 16 mm board and its pads ring the
    edge. It gets no body but stays a component. U2, a module covering a fifth of the board,
    and R1 get bodies, and so does U3, a board-sized shield whose height the file gives.
    """
    d = Doc()
    d.line_desc("OUTLINE", 0.1)
    d.primitive("PAD", f'<RectCenter width="{d.u(1.0)}" height="{d.u(1.0)}"/>')
    two_layers(d, drill=False)
    profile(d, 20, 16)
    packages = {
        "MODULE_BOARD": ((-10, -8, 10, 8), [(-9, -7), (9, -7), (9, 7), (-9, 7)]),
        "MODULE_8X8": ((-4, -4, 4, 4), [(-3, -3), (3, -3), (3, 3), (-3, 3)]),
        "R0603": ((-1.2, -0.6, 1.2, 0.6), [(-0.8, 0), (0.8, 0)]),
        "SHIELD_BOARD": ((-10, -8, 10, 8), [(-9, 0), (9, 0)]),
    }
    for name, (box, pins) in packages.items():
        pin_xml = "".join(
            f'<Pin number="{n}"><Location {d.xy(x, y)}/><StandardPrimitiveRef id="PAD"/></Pin>'
            for n, (x, y) in enumerate(pins, 1)
        )
        d.step.append(
            f'<Package name="{name}" type="OTHER" pinOne="1">'
            f'<Outline><Polygon>{d.rect(*box)}</Polygon><LineDescRef id="OUTLINE"/></Outline>'
            f"{pin_xml}</Package>"
        )
    pads = []
    parts = [
        ("U1", "MODULE_BOARD", 10, 8, ""),
        ("U2", "MODULE_8X8", 7, 8, ""),
        ("R1", "R0603", 15, 8, ""),
        ("U3", "SHIELD_BOARD", 10, 8, f' height="{d.u(1.5)}"'),
    ]
    for ref, package, x, y, height in parts:
        d.step.append(
            f'<Component refDes="{ref}" packageRef="{package}" layerRef="TOP" mountType="SMT"{height}>'
            f"<Location {d.xy(x, y)}/></Component>"
        )
        for n, (px, py) in enumerate(packages[package][1], 1):
            pads.append(f'<Set padUsage="TERMINATION">{pad(d, x + px, y + py, "PAD", (ref, str(n)))}</Set>')
    d.step.append(f'<LayerFeature layerRef="TOP">{"".join(pads)}</LayerFeature>')
    return d


def text_element(d, string, box, font=None, xform="", color=""):
    """A `Text` in `box` (x0, y0, x1, y1); non-ASCII characters as character references."""
    x0, y0, x1, y1 = box
    string = escape(string, {'"': "&quot;"}).encode("ascii", "xmlcharrefreplace").decode()
    font_ref = f'<FontRef id="{font}"/>' if font else ""
    return (
        f'<Text textString="{string}" fontSize="{max(1, round(y1 - y0))}">{xform}'
        f'<BoundingBox lowerLeftX="{d.u(x0)}" lowerLeftY="{d.u(y0)}" '
        f'upperRightX="{d.u(x1)}" upperRightY="{d.u(y1)}"/>{font_ref}{color}</Text>'
    )


def text():
    """`Text` in an embedded font, in the bundled font for an external font and without one,
    rotated, mirrored, too wide for its box, with Latin-1 and unknown characters, on
    copper: cut by a hole, and knocked out of a plane, and in a package's assembly drawing,
    placed with its rotated part on `@assembly-top` (spec §6.6, §6.13, §8.2)."""
    d = Doc()
    d.line_desc("UNDERLINE", 0.3)
    d.line_desc("OUTLINE", 0.1)
    d.primitive("PAD", f'<RectCenter width="{d.u(0.9)}" height="{d.u(1.2)}"/>')
    d.layer("TOP", "CONDUCTOR", "TOP")
    d.layer("BOTTOM", "CONDUCTOR", "BOTTOM")
    d.layer("DRILL", "DRILL", "ALL", span=("TOP", "BOTTOM"))
    d.layer("SILK", "SILKSCREEN", "TOP")
    profile(d, 50, 34)

    # A plotter font in a 1 mm design: capitals 1 high on the baseline, descenders to -0.2.
    stroke = f'<LineDesc lineWidth="{d.u(0.12)}" lineEnd="ROUND"/>'

    def path(points):
        """A path from points and (x, y, centerX, centerY) clockwise arcs."""
        (x0, y0), rest = points[0], points[1:]
        steps = "".join(
            f"<PolyStepSegment {d.xy(*p)}/>"
            if len(p) == 2
            else f'<PolyStepCurve {d.xy(*p[:2])} centerX="{d.u(p[2])}" '
            f'centerY="{d.u(p[3])}" clockwise="true"/>'
            for p in rest
        )
        return f"<Polyline><PolyBegin {d.xy(x0, y0)}/>{steps}{stroke}</Polyline>"

    def line(x0, y0, x1, y1):
        return (
            f'<Line startX="{d.u(x0)}" startY="{d.u(y0)}" endX="{d.u(x1)}" endY="{d.u(y1)}">'
            f"{stroke}</Line>"
        )

    def glyph(code, width, *shapes):
        return (
            f'<Glyph charCode="{code}" lowerLeftX="0" lowerLeftY="{d.u(-0.2)}" '
            f'upperRightX="{d.u(width)}" upperRightY="{d.u(1)}">{"".join(shapes)}</Glyph>'
        )

    o = path([(0.15, 0.3), (0.15, 0.7), (0.65, 0.7, 0.4, 0.7), (0.65, 0.3), (0.15, 0.3, 0.4, 0.3)])
    glyphs = [
        glyph("20", 0.5),
        glyph(
            "41",
            0.8,
            path([(0.05, 0), (0.4, 1), (0.75, 0)]),
            line(0.17, 0.35, 0.63, 0.35),
        ),
        glyph(
            "42",
            0.8,
            path([(0.1, 0), (0.1, 1), (0.42, 1), (0.42, 0.5, 0.42, 0.75), (0.1, 0.5)]),
            path([(0.1, 0.5), (0.47, 0.5), (0.47, 0, 0.47, 0.25), (0.1, 0)]),
        ),
        glyph("44", 0.8, path([(0.1, 0), (0.1, 1), (0.25, 1), (0.25, 0, 0.25, 0.5), (0.1, 0)])),
        glyph("4F", 0.8, o),
        glyph(
            "52",
            0.8,
            path([(0.1, 0), (0.1, 1), (0.42, 1), (0.42, 0.5, 0.42, 0.75), (0.1, 0.5)]),
            line(0.35, 0.5, 0.65, 0),
        ),
        # Ø, with a four-digit charCode.
        glyph("00D8", 0.8, o, line(0.1, -0.05, 0.7, 1.05)),
    ]
    d.font(
        "PLOTTER",
        f'<FontDefEmbedded name="plotter">{stroke}{"".join(glyphs)}</FontDefEmbedded>',
    )
    d.font("ARIAL", '<FontDefExternal name="Arial" urn="urn:example:font:arial"/>')

    # A part whose assembly drawing has its reference designator as a Text marking.
    refdes = text_element(d, "U1", (-0.5, -0.3, 0.5, 0.3))
    drawing = (
        f'<AssemblyDrawing><Outline><Polygon>{d.rect(-1.0, -0.6, 1.0, 0.6)}</Polygon>'
        f'<LineDescRef id="OUTLINE"/></Outline>'
        f'<Marking markingUsage="REFDES">{refdes}</Marking></AssemblyDrawing>'
    )
    two_pin_package(d, "U0805", drawing)
    pads = {"TOP": []}
    place_two_pin(d, [("U1", "TOP", 44, 7, 90, False)], "U0805", pads)

    def features(inner, x=0, y=0):
        return f"<Features><Location {d.xy(x, y)}/>{inner}</Features>"

    silk = [
        # Embedded glyphs; `2` is not in the font and comes from the bundled one.
        text_element(d, "BOARD Ø2", (2, 28.5, 32, 32.5), font="PLOTTER"),
        # An external font is drawn with the bundled font.
        text_element(
            d, "External font: Arial", (2, 24, 40, 27), font="ARIAL",
            color='<ColorTerm name="WHITE"/>',
        ),
        # Latin-1 in the bundled font; Ω has no glyph and is drawn as a box.
        text_element(d, "Ærøskøbing µ±0.1° Ω", (2, 19, 42, 22)),
        # Wider than its box: scaled down to fit.
        text_element(d, "Too wide for its box", (18, 14.5, 38, 17)),
    ]
    mirrored = text_element(d, "Mirror", (0, 0, 12, 2.5), xform='<Xform mirror="true"/>')
    rotated = text_element(
        d, "R90", (0, 0, 14, 2.5),
        xform=f'<Xform xOffset="{d.u(47)}" yOffset="{d.u(14)}" rotation="90"/>',
    )
    d.step.append(
        '<LayerFeature layerRef="SILK">'
        + "".join(f"<Set>{features(t)}</Set>" for t in silk)
        + f"<Set>{features(mirrored, 14, 14.5)}</Set>"
        + f"<Set>{features(rotated)}</Set>"
        + "</LayerFeature>"
    )
    # Copper text with an underline in one feature, cut by a hole through the stem of the N,
    # and text knocked out of a plane.
    underline = (
        f'<Line startX="{d.u(2)}" startY="{d.u(3.3)}" endX="{d.u(9.5)}" endY="{d.u(3.3)}">'
        '<LineDescRef id="UNDERLINE"/></Line>'
    )
    gnd = text_element(d, "GND", (2, 3, 14, 6))
    knockout = text_element(d, "CUT", (22, 3.5, 36, 6.5))
    d.step.append(
        '<LayerFeature layerRef="TOP">'
        f'<Set net="GND">{features(f"<UserSpecial>{gnd}{underline}</UserSpecial>")}</Set>'
        f'<Set net="GND">{fill(d, 20, 2, 38, 8)}</Set>'
        f'<Set polarity="NEGATIVE">{features(knockout)}</Set>'
        f'{"".join(pads["TOP"])}'
        "</LayerFeature>"
    )
    d.step.append(
        '<LayerFeature layerRef="DRILL"><Set>'
        f'<Hole name="H1" diameter="{d.u(0.6)}" platingStatus="NONPLATED" plusTol="0" '
        f'minusTol="0" {d.xy(4.79, 4.9)}/>'
        "</Set></LayerFeature>"
    )
    return d


def box_model():
    """A 1.6 × 0.8 × 0.5 mm box as a .gltf with an embedded buffer, in metres."""
    (x, z, h) = (0.8e-3, 0.4e-3, 0.5e-3)
    corners = [(sx * x, y, sz * z) for y in (0.0, h) for sz in (-1, 1) for sx in (-1, 1)]
    # Faces as quads of corner indices, counter-clockwise from outside.
    quads = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    indices = [i for a, b, c, e in quads for i in (a, b, c, a, c, e)]
    data = b"".join(struct.pack("<3f", *c) for c in corners)
    data += b"".join(struct.pack("<H", i) for i in indices)
    uri = "data:application/octet-stream;base64," + base64.b64encode(data).decode()
    gltf = {
        "asset": {"version": "2.0", "generator": "boardui samples"},
        "scene": 0,
        "scenes": [{"nodes": [0]}],
        "nodes": [{"name": "box", "mesh": 0}],
        "meshes": [{"primitives": [{"attributes": {"POSITION": 0}, "indices": 1, "material": 0}]}],
        "materials": [
            {"name": "ceramic", "pbrMetallicRoughness": {"baseColorFactor": [0.55, 0.45, 0.3, 1], "metallicFactor": 0}}
        ],
        "accessors": [
            {"bufferView": 0, "componentType": 5126, "count": 8, "type": "VEC3",
             "min": [-x, 0, -z], "max": [x, h, z]},
            {"bufferView": 1, "componentType": 5123, "count": len(indices), "type": "SCALAR"},
        ],
        "bufferViews": [
            {"buffer": 0, "byteLength": 96, "target": 34962},
            {"buffer": 0, "byteOffset": 96, "byteLength": 2 * len(indices), "target": 34963},
        ],
        "buffers": [{"byteLength": len(data), "uri": uri}],
    }
    return json.dumps(gltf, indent=1) + "\n"


def colours():
    """Soldermask and silkscreen colours from specs and the colour dictionary (spec §6.10)."""
    d = Doc()
    d.line_desc("TRACE", 0.3)
    d.line_desc("SILK", 0.15)
    d.primitive("PAD", f'<RectCenter width="{d.u(1.2)}" height="{d.u(1.4)}"/>')
    d.color("MASK_RGB", 90, 30, 120)
    d.color("COPPER_RGB", 255, 0, 0)
    # Top mask: an explicit colour wins over a colour name in the same spec.
    d.spec(
        "MASK_TOP",
        '<General type="MATERIAL"><Property text="Color : Red"/><ColorRef id="MASK_RGB"/></General>',
    )
    # Top silkscreen: a standard ColorTerm.
    d.spec("SILK_TOP", '<General type="MATERIAL"><ColorTerm name="YELLOW"/></General>')
    # Copper keeps its default even with a colour.
    d.spec("COPPER", '<General type="MATERIAL"><ColorRef id="COPPER_RGB"/></General>')
    # Bottom mask as KiCad 9 writes it: the stack-up refers to `SPEC_SMB`, the spec is `SMB_2`.
    d.spec(
        "SMB_2",
        '<General type="MATERIAL"><Property text="SOLDERMASK"/>'
        '<Property text="Color : Matte Black"/><Property text="Type : Bottom Solder Mask"/></General>',
    )
    # Bottom silkscreen: a name that maps to the default colour.
    d.spec("SILK_BOTTOM", '<General type="MATERIAL"><Property text="Color : White"/></General>')
    d.layer("SST", "SILKSCREEN", "TOP", specs=["SILK_TOP"])
    d.layer("SMT", "SOLDERMASK", "TOP", specs=["MASK_TOP"])
    d.layer("TOP", "CONDUCTOR", "TOP", specs=["COPPER"])
    d.layer("CORE", "DIELCORE", "INTERNAL")
    d.layer("BOTTOM", "CONDUCTOR", "BOTTOM")
    d.layer("SMB", "SOLDERMASK", "BOTTOM")
    d.layer("SSB", "SILKSCREEN", "BOTTOM", specs=["SILK_BOTTOM"])
    stack = [("SST", 0.01), ("SMT", 0.02), ("TOP", 0.035), ("CORE", 1.51)]
    stack += [("BOTTOM", 0.035), ("SMB", 0.02), ("SSB", 0.01)]
    rows = "".join(
        f'<StackupLayer layerOrGroupRef="{name}" thickness="{d.u(t)}" tolPlus="0" tolMinus="0"'
        f' sequence="{i}"' + ('><SpecRef id="SPEC_SMB"/></StackupLayer>' if name == "SMB" else "/>")
        for i, (name, t) in enumerate(stack)
    )
    d.layers.append(
        f'<Stackup name="S" overallThickness="{d.u(1.64)}" tolPlus="0" tolMinus="0" whereMeasured="MASK">'
        f'<StackupGroup name="G" thickness="{d.u(1.64)}" tolPlus="0" tolMinus="0">{rows}</StackupGroup></Stackup>'
    )
    profile(d, 10, 6)
    pads = "".join(pad(d, x, 3, "PAD") for x in (3, 7))
    outline = trace(d, [(1, 1), (9, 1), (9, 5), (1, 5), (1, 1)], "SILK")
    d.step += [
        # Cadence writes the CAD tool's display colour on a layer's first `Set`: not used.
        f'<LayerFeature layerRef="TOP"><Set><ColorRef id="COPPER_RGB"/></Set>'
        f'<Set net="N">{pads}{trace(d, [(3, 3), (7, 3)], "TRACE")}</Set></LayerFeature>',
        f'<LayerFeature layerRef="SMT"><Set>{pads}</Set></LayerFeature>',
        f'<LayerFeature layerRef="SST"><Set>{outline}</Set></LayerFeature>',
        f'<LayerFeature layerRef="BOTTOM"><Set net="N">{fill(d, 2, 2, 8, 4)}</Set></LayerFeature>',
        f'<LayerFeature layerRef="SSB"><Set>{outline}</Set></LayerFeature>',
    ]
    return d


